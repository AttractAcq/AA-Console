import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const output = resolve(root, "src/compositions/v2-fixture.generated.ts");
const ir = JSON.parse(await readFile(resolve(root, "fixtures/ir/gold-v2.json"), "utf8"));
const timings = JSON.parse(await readFile(resolve(root, "fixtures/timings/gold-v2.json"), "utf8"));
const content = `// Generated by scripts/export-v2-fixture.mjs. Do not edit.\nexport const V2_FIXTURE = ${JSON.stringify({ ir, timings }, null, 2)} as const;\n`;
if (process.argv.includes("--check")) {
  if (await readFile(output, "utf8") !== content) throw new Error("V2 fixture module differs from source JSON");
} else {
  await writeFile(output, content);
}
